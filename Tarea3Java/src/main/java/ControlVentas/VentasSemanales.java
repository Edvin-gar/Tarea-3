    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
double totalVendido = 0;
    int ventasSuperioresMeta = 0;

    // 1. Recorrer el arreglo para hacer los cálculos
    for (int i = 0; i < ventas.length; i++) {
        totalVendido += ventas[i];
        if (ventas[i] > 500.00) {
            ventasSuperioresMeta++;
        }
    }

    try (java.io.BufferedWriter writer = new java.io.BufferedWriter(new java.io.FileWriter("temp/Edvin_reporte_ventas.txt"))) {
        writer.write("Reporte de Ventas\n");
        writer.write("Total Vendido: " + totalVendido + "\n");
        writer.write("Ventas superiores a Q500: " + ventasSuperioresMeta);
        
        javax.swing.JOptionPane.showMessageDialog(this, "Reporte guardado con éxito.");
    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el archivo.");
    }
    }//GEN-LAST:event_btnGenerarReporteActionPerformed

