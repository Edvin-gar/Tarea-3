    private void btnCargarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarDatosActionPerformed

        // TODO add your handling code here:
        try (BufferedReader br = new BufferedReader(new FileReader(rutaArchivo))) {
    String linea;
    indice = 0; // Reiniciamos el índice por si se vuelve a cargar

    while ((linea = br.readLine()) != null && indice < 6) {
        temperaturas[indice] = Double.parseDouble(linea.trim());
        indice++;
    }

    if (indice == 6) {
        JOptionPane.showMessageDialog(this, "Los datos fueron cargados en memoria.", 
                "Éxito", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(this, "El archivo no contiene los 6 registros requeridos.", 
                "Advertencia", JOptionPane.WARNING_MESSAGE);
    }

} catch (IOException e) {
    JOptionPane.showMessageDialog(this, "Error al abrir o leer el archivo: " + e.getMessage(), 
            "Error de Archivo", JOptionPane.ERROR_MESSAGE);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "El archivo contiene datos que no son números válidos.", 
            "Error de Formato", JOptionPane.ERROR_MESSAGE);
}
        
        
    }//GEN-LAST:event_btnCargarDatosActionPerformed

    private void btnCalcularEstadisticasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularEstadisticasActionPerformed
        // TODO add your handling code here:
        if (indice < 6) {
    JOptionPane.showMessageDialog(this, "Primero debe cargar los datos del archivo.", 
            "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

double suma = 0;
int diasCalidos = 0;
int diasFrescos = 0;

for (int i = 0; i < temperaturas.length; i++) {
    suma += temperaturas[i];

    if (temperaturas[i] >= 25.0) {
        diasCalidos++;
    } else {
        diasFrescos++;
    }
}

double promedio = suma / temperaturas.length;

txtResultados.setText("");
txtResultados.append("Análisis Climático\n");
txtResultados.append("------------------\n");
txtResultados.append("Promedio de Temperatura: " + String.format("%.1f", promedio) + "\n");
txtResultados.append("Días Cálidos (>= 25°): " + diasCalidos + "\n");
txtResultados.append("Días Frescos (< 25°): " + diasFrescos + "\n");
        
        
    }//GEN-LAST:event_btnCalcularEstadisticasActionPerformed

