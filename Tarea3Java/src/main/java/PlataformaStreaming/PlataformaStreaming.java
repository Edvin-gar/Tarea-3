    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
                                                    
    String nom = txtArtNombre.getText();
    String pais = txtArtPais.getText();
    int oyentes = Integer.parseInt(txtArtOyentes.getText());

    Artista art = new Artista();
    art.nombre = nom;
    art.paisOrigen = pais;
    art.oyentesMensuales = oyentes;

    txtResultados.append("Artista: " + art.nombre + " (" + art.paisOrigen + ") - " + art.oyentesMensuales + " oyentes\n");
    
    txtArtNombre.setText("");
            txtArtPais.setText("");
            txtArtOyentes.setText("");

    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
                                        
       String tit = txtCanTitulo.getText();
    String art = txtCanArtista.getText();
    int dur = Integer.parseInt(txtCanDuracion.getText());
    String gen = txtCanGenero.getText();

    // 2. Instanciar y asignar con operador punto
    Cancion can = new Cancion();
    can.titulo = tit;
    can.nombreArtista = art;
    can.duracionSegundos = dur;
    can.genero = gen;

    // 3. Imprimir usando .append()
    txtResultados.append("Canción: " + can.titulo + " por " + can.nombreArtista + " [" + can.genero + ", " + can.duracionSegundos + "s]\n");
     
     txtCanTitulo.setText("");
            txtCanArtista.setText("");
            txtCanDuracion.setText("");
            txtCanGenero.setText("");
    
    }//GEN-LAST:event_btnCrearCancionActionPerformed

