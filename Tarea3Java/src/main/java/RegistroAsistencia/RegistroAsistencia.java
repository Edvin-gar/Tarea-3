    private void btnRegistrarAsistenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarAsistenteActionPerformed

        if (indice >= 5) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ya se han registrado los 5 asistentes permitidos.", "Límite alcanzado", javax.swing.JOptionPane.WARNING_MESSAGE);
        txtNombre.setText("");
        return;
    }
         String nombre = txtNombre.getText().trim();
    if (nombre.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese un nombre válido.", "Campo vacío", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }
     asistentes[indice] = nombre;
    indice++;
     txtLista.setText(""); 
    for (int i = 0; i < indice; i++) {
        txtLista.append((i + 1) + ". " + asistentes[i] + "\n");
    }
     txtNombre.setText("");
    txtNombre.requestFocus();
    }//GEN-LAST:event_btnRegistrarAsistenteActionPerformed

    private void btnExportarListaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarListaActionPerformed
    
        if (indice < 5) {
        javax.swing.JOptionPane.showMessageDialog(this, "Debe registrar exactamente 5 asistentes antes de exportar. Faltan: " + (5 - indice), "Registro incompleto", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
       String rutaArchivo = System.getProperty("user.dir") + "/temp/edvin_asistencia.txt";

       try (java.io.BufferedWriter bw = new java.io.BufferedWriter(new java.io.FileWriter(rutaArchivo))) {
        bw.write("Lista de Asistencia");
        bw.newLine();

        for (int i = 0; i < asistentes.length; i++) {
            bw.write((i + 1) + ". " + asistentes[i]);
            bw.newLine();
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Archivo guardado exitosamente en:\n" + rutaArchivo, "Exportación Exitosa", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    } 
    }//GEN-LAST:event_btnExportarListaActionPerformed

