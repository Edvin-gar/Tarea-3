    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        
        String busqueda = txtBuscarAlbum.getText().trim();
    indiceEncontrado = -1; 

    if (busqueda.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, ingrese un álbum a buscar.");
        return;
    }

    for (int i = 0; i < titulos.length; i++) {
        if (titulos[i] != null && titulos[i].equalsIgnoreCase(busqueda)) {
            indiceEncontrado = i; 
            break; 
        }
    }

   
    if (indiceEncontrado != -1) {
        lblAnioActual.setText("Año Actual: " + anios[indiceEncontrado]);
        txtNuevoAnio.setText(String.valueOf(anios[indiceEncontrado]));
    } else {
        lblAnioActual.setText("Año Actual: --");
        JOptionPane.showMessageDialog(this, "Álbum no encontrado.");
    }
    
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarRegistroActionPerformed
        // TODO add your handling code here:
        
        if (indiceEncontrado == -1) {
        JOptionPane.showMessageDialog(this, "Debe buscar y encontrar un álbum antes de actualizar.");
        return;
    }

    try {
        
        int nuevoAnio = Integer.parseInt(txtNuevoAnio.getText().trim());
        anios[indiceEncontrado] = nuevoAnio;
        lblAnioActual.setText("Año Actual: " + nuevoAnio); 

  
        File archivo = new File("discos.csv");
        FileWriter fw = new FileWriter(archivo, false); 
        PrintWriter pw = new PrintWriter(fw);

        for (int i = 0; i < titulos.length; i++) {
            if (titulos[i] != null) {
                pw.println(titulos[i] + "," + anios[i]);
            }
        }
        pw.close();

        JOptionPane.showMessageDialog(this, "¡Registro actualizado y guardado en discos.csv con éxito!");
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Por favor, ingrese un número de año válido.");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    }
    
    }//GEN-LAST:event_btnActualizarRegistroActionPerformed

