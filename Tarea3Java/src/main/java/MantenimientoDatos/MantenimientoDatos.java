        private void cargarDatosAutomaticamente() {
        File archivo = new File("discos.csv");
        try {
            // Si el archivo NO existe, crea uno automáticamente con 5 ejemplos
            if (!archivo.exists()) {
                FileWriter fw = new FileWriter(archivo);
                PrintWriter pw = new PrintWriter(fw);
                pw.println("Abbey Road,1969");
                pw.println("The Dark Side of the Moon,1973");
                pw.println("Thriller,1982");
                pw.println("Back in Black,1980");
                pw.println("Nevermind,1991");
                pw.close();
            }

           
            Scanner sc = new Scanner(archivo);
            int i = 0;
            while (sc.hasNextLine() && i < 5) {
                String linea = sc.nextLine();
                String[] partes = linea.split(","); 
                
                titulos[i] = partes[0];
                anios[i] = Integer.parseInt(partes[1].trim());
                i++;
            }
            sc.close();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar el archivo: " + e.getMessage());
        }
    }
        
