    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        
        try {
    String t = txtTitulo.getText();
    String c = txtConsola.getText();
    int a = Integer.parseInt(txtAnio.getText());

    
    catalogo.add(new Videojuego(t, c, a));

    
    txtTitulo.setText(""); txtConsola.setText(""); txtAnio.setText("");
    javax.swing.JOptionPane.showMessageDialog(this, "¡Guardado con éxito!");
} catch(Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Verifica los datos introducidos.");
}

        
        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (catalogo.size() > 0) {
    
    catalogo.remove(catalogo.size() - 1);
    javax.swing.JOptionPane.showMessageDialog(this, "Se eliminó el último videojuego.");
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "El catálogo está vacío.");
}

        
        
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        
        txtArea.setText(""); 


for (int i = 0; i < catalogo.size(); i++) {
    Videojuego v = catalogo.get(i);
    txtArea.append(v.titulo + " (" + v.consola + ") - Año: " + v.anio + "\n");
}


txtArea.append("\nTotal de juegos: " + catalogo.size());

        
    }//GEN-LAST:event_btnMostrarActionPerformed

